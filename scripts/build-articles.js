#!/usr/bin/env node
/* =====================================================================
   build-articles.mjs — turns the plain-text posts in /articles into the
   files the website actually serves. No dependencies: plain Node 18+.

     articles/*.md        (you write these)
        |
        v
     newsroom/<slug>.html one real page per post, with its own title,
                          description and share image for link previews
     hlw-articles.js      the list of posts (no body text) that the
                          newsroom page, homepage card stack and marquee read

   Run it by hand:   node scripts/build-articles.mjs
   On GitHub it runs automatically whenever something in /articles
   changes (.github/workflows/build-newsroom.yml) and commits the result.

   Never edit newsroom/*.html or hlw-articles.js by hand — they are
   rewritten every time. Edit the .md file instead.
   ===================================================================== */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// `--root <dir>` points the script at another copy of the site (used for testing)
const rootArg = process.argv.indexOf('--root');
const ROOT = rootArg > -1 ? process.argv[rootArg + 1] : join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(ROOT, 'articles');
const OUT_DIR = join(ROOT, 'newsroom');
const DATA_FILE = join(ROOT, 'hlw-articles.js');
const SITE_URL = (process.env.SITE_URL || 'https://haydenharms.github.io/hlwfinancial/').replace(/\/?$/, '/');
const DEFAULT_SHARE_IMAGE = 'media/social-preview.jpg';
const GENERATED_MARK = 'GENERATED by scripts/build-articles.mjs';

const MONTHS = ['January','February','March','April','May','June','July','August','September','October','November','December'];
const errors = [];
const fail = (file, msg) => errors.push(`articles/${file}: ${msg}`);
const pad = n => String(n).padStart(2, '0');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/* ---------- front matter ---------- */
function parseFile(file, text){
  text = text.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  const m = /^---\n([\s\S]*?)\n---[ \t]*(?:\n|$)([\s\S]*)$/.exec(text);
  if(!m){ fail(file, 'must start with a front matter block: a line of ---, the details, then another line of ---'); return null; }
  const meta = {};
  for(const line of m[1].split('\n')){
    if(!line.trim() || line.trim().startsWith('#')) continue;
    const i = line.indexOf(':');
    if(i < 1){ fail(file, `can't read this front matter line: "${line}" (it should look like  key: value)`); return null; }
    const key = line.slice(0, i).trim();
    let val = line.slice(i + 1).trim();
    if((val.startsWith('"') && val.endsWith('"') && val.length > 1) || (val.startsWith("'") && val.endsWith("'") && val.length > 1)) val = val.slice(1, -1);
    meta[key] = val;
  }
  return { meta, body: m[2].trim() };
}

/* ---------- dates: 2026-08 | 2026-08-14 | Aug 2026 | August 14, 2026 ---------- */
function parseDate(str){
  const mk = (y, mo, d) => (mo >= 1 && mo <= 12 && (d == null || (d >= 1 && d <= 31))) ? { year: y, month: mo, day: d } : null;
  let m = /^(\d{4})-(\d{1,2})(?:-(\d{1,2}))?$/.exec(str);
  if(m) return mk(+m[1], +m[2], m[3] ? +m[3] : null);
  m = /^([A-Za-z]{3,9})\.?\s+(?:(\d{1,2}),?\s+)?(\d{4})$/.exec(str);
  if(m){
    const mi = MONTHS.findIndex(n => n.slice(0, 3).toLowerCase() === m[1].slice(0, 3).toLowerCase());
    if(mi > -1) return mk(+m[3], mi + 1, m[2] ? +m[2] : null);
  }
  return null;
}
function dateFields(d){
  const short = MONTHS[d.month - 1].slice(0, 3);
  return {
    date: d.day ? `${short} ${d.day}, ${d.year}` : `${short} ${d.year}`,
    dateNumeric: d.day ? `${pad(d.month)} / ${pad(d.day)} / ${d.year}` : `${pad(d.month)} / ${d.year}`,
    dateISO: d.day ? `${d.year}-${pad(d.month)}-${pad(d.day)}` : `${d.year}-${pad(d.month)}`,
    groupKey: `${d.year}-${pad(d.month)}`,
    groupLabel: `${MONTHS[d.month - 1]} ${d.year}`
  };
}

/* ---------- small markdown -> HTML (paragraphs, ## headings, lists, quotes, links, bold, italics, images, ---) ----------
   Anything else is escaped, so a stray < or & in a post can't break the page. */
function safeUrl(u){
  u = u.trim();
  // web links, email, phone, #anchors and relative paths are fine; any other scheme (javascript:, data:, ...) is not
  return (/^[a-z][a-z0-9+.\-]*:/i.test(u) && !/^(https?|mailto|tel):/i.test(u)) ? '#' : u;
}
function inline(text){
  const codes = [];
  let s = esc(text).replace(/`([^`]+)`/g, (_, c) => { codes.push(c); return `\u0000${codes.length - 1}\u0000`; });
  s = s.replace(/!\[([^\]]*)\]\(([^)\s]+)(?:\s+&quot;([^&]*)&quot;)?\)/g, (_, alt, url, title) =>
        `<img src="${safeUrl(url)}" alt="${alt}"${title ? ` title="${title}"` : ''} loading="lazy">`)
   .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, url) => {
        const u = safeUrl(url);
        return `<a href="${u}"${/^https?:/i.test(u) ? ' rel="noopener"' : ''}>${label}</a>`;
      })
   .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
   .replace(/(^|[^*\w])\*([^*\n]+)\*(?!\*)/g, '$1<em>$2</em>')
   .replace(/(^|[^\w])_([^_\n]+)_(?!\w)/g, '$1<em>$2</em>');
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${codes[+i]}</code>`);
}
function markdown(src){
  const lines = src.split('\n');
  const out = [];
  let i = 0;
  while(i < lines.length){
    const line = lines[i];
    if(!line.trim()){ i++; continue; }
    let m;
    if((m = /^(#{1,4})\s+(.*)$/.exec(line))){                      // # and ## both become <h2>, ### <h3>, #### <h4> (the page title is the h1)
      const level = Math.max(2, m[1].length === 1 ? 2 : m[1].length);
      out.push(`<h${level}>${inline(m[2].trim())}</h${level}>`); i++; continue;
    }
    if(/^(-{3,}|\*{3,})\s*$/.test(line)){ out.push('<hr>'); i++; continue; }
    if(/^>\s?/.test(line)){
      const q = [];
      while(i < lines.length && /^>\s?/.test(lines[i])){ q.push(lines[i].replace(/^>\s?/, '')); i++; }
      out.push(`<blockquote><p>${inline(q.join(' '))}</p></blockquote>`); continue;
    }
    if(/^\s*[-*]\s+/.test(line)){
      const items = [];
      while(i < lines.length && /^\s*[-*]\s+/.test(lines[i])){ items.push(`<li>${inline(lines[i].replace(/^\s*[-*]\s+/, ''))}</li>`); i++; }
      out.push(`<ul>${items.join('')}</ul>`); continue;
    }
    if(/^\s*\d+[.)]\s+/.test(line)){
      const items = [];
      while(i < lines.length && /^\s*\d+[.)]\s+/.test(lines[i])){ items.push(`<li>${inline(lines[i].replace(/^\s*\d+[.)]\s+/, ''))}</li>`); i++; }
      out.push(`<ol>${items.join('')}</ol>`); continue;
    }
    const para = [];
    while(i < lines.length && lines[i].trim() && !/^(#{1,4}\s|>|\s*[-*]\s+|\s*\d+[.)]\s+|-{3,}\s*$|\*{3,}\s*$)/.test(lines[i])){ para.push(lines[i].trim()); i++; }
    out.push(`<p>${inline(para.join(' '))}</p>`);
  }
  return out.join('\n');
}
const plainText = md => md.replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/[*_`#>]/g, '').replace(/\s+/g, ' ').trim();
function firstParagraph(body){
  const p = body.split(/\n\s*\n/).find(b => b.trim() && !/^(#|>|-{3,}|\s*[-*]\s|\s*\d+[.)]\s|!\[)/.test(b.trim()));
  return p ? plainText(p) : '';
}
function truncate(s, n){
  if(s.length <= n) return s;
  const cut = s.slice(0, n).replace(/\s+\S*$/, '');
  return cut.replace(/[.,;:\-\u2014\s]+$/, '') + '\u2026';
}

/* ---------- read every post ---------- */
if(!existsSync(SRC_DIR)){ console.error(`No articles folder found at ${SRC_DIR}`); process.exit(1); }
const posts = [];
const seen = new Set();
for(const file of readdirSync(SRC_DIR).sort()){
  if(!file.endsWith('.md') || file.startsWith('_') || file.toLowerCase() === 'readme.md') continue;   // README.md and _template.md are not posts
  const slug = file.slice(0, -3);
  if(!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)){ fail(file, `the file name must be lowercase letters, numbers and dashes only (like  founding-clients.md)`); continue; }
  if(seen.has(slug)){ fail(file, 'duplicate file name'); continue; }
  seen.add(slug);
  const parsed = parseFile(file, readFileSync(join(SRC_DIR, file), 'utf8'));
  if(!parsed) continue;
  const { meta, body } = parsed;
  if(/^(true|yes)$/i.test(meta.draft || '')) continue;                                                 // draft: true  -> not published
  const need = ['title', 'date', 'category'].filter(k => !meta[k]);
  if(need.length){ fail(file, `missing ${need.join(', ')} in the front matter`); continue; }
  const d = parseDate(meta.date);
  if(!d){ fail(file, `can't read the date "${meta.date}" (use something like 2026-08, 2026-08-14, Aug 2026 or Aug 14, 2026)`); continue; }
  if(!body){ fail(file, 'the post has no text below the front matter'); continue; }
  let tags = [];
  if(meta.tags){ tags = meta.tags.replace(/^\[|\]$/g, '').split(',').map(t => t.trim().replace(/^["']|["']$/g, '')).filter(Boolean); }
  if(!tags.length) tags = [meta.category];
  posts.push({
    slug, d, body, meta, tags,
    excerpt: meta.excerpt || truncate(firstParagraph(body), 200)
  });
}
if(errors.length){
  console.error('\nThe newsroom was NOT rebuilt. Fix these and push again:\n' + errors.map(e => '  - ' + e).join('\n') + '\n');
  process.exit(1);
}

// newest first; posts from the same day/month keep a steady order by file name
posts.sort((a, b) => (b.d.year - a.d.year) || (b.d.month - a.d.month) || ((b.d.day || 0) - (a.d.day || 0)) || a.slug.localeCompare(b.slug));

/* ---------- one page per post ---------- */
function pageHtml(p, a){
  const url = `${SITE_URL}newsroom/${p.slug}.html`;
  const image = p.meta.image ? SITE_URL + p.meta.image.replace(/^\//, '') : SITE_URL + DEFAULT_SHARE_IMAGE;
  const title = `${p.meta.title} \u2014 HLW Financial`;
  const tagsHtml = a.tags.map(t => `<li class="art-tag">${esc(t)}</li>`).join('');
  return `<!DOCTYPE html>
<html lang="en">
<head>
<!-- ${GENERATED_MARK} from articles/${p.slug}.md. Do not edit this file; edit the .md file. -->
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<base href="../">
<title>${esc(title)}</title>
<meta name="description" content="${esc(a.excerpt)}">
<link rel="canonical" href="${esc(url)}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(a.excerpt)}">
<meta property="og:image" content="${esc(image)}">${p.meta.image ? '' : '\n<meta property="og:image:width" content="1187">\n<meta property="og:image:height" content="1200">'}
<meta property="og:type" content="article">
<meta property="og:url" content="${esc(url)}">
<meta property="article:published_time" content="${a.dateISO}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(a.excerpt)}">
<meta name="twitter:image" content="${esc(image)}">
<link rel="icon" type="image/svg+xml" href="media/favicon.svg">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
<link rel="stylesheet" href="hlw-chrome.css">
<link rel="stylesheet" href="hlw-article.css">
</head>
<body>

<header class="site-nav" id="siteNav" data-nav-mode="light"></header>

<main class="art">
  <div class="art-side">
    <div class="art-date">${esc(a.dateNumeric)}</div>
    <h1>${esc(p.meta.title)}</h1>
    <ul class="art-tags">${tagsHtml}</ul>
    <a class="art-back" href="news.html">\u2190 The Newsroom</a>
  </div>
  <div class="art-body">
${markdown(p.body)}
  </div>
</main>

<div class="footer" id="siteFooter"></div>

<div id="gsModalMount"></div>

<script src="hlw-chrome.js"></script>
</body>
</html>
`;
}

/* ---------- write everything ---------- */
mkdirSync(OUT_DIR, { recursive: true });
const wanted = new Set(posts.map(p => `${p.slug}.html`));
for(const f of readdirSync(OUT_DIR)){                                                                    // remove pages of posts that were deleted or turned into drafts
  if(f.endsWith('.html') && !wanted.has(f) && readFileSync(join(OUT_DIR, f), 'utf8').includes(GENERATED_MARK)) rmSync(join(OUT_DIR, f));
}

const index = posts.map(p => {
  const f = dateFields(p.d);
  const a = {
    id: p.slug,
    url: `newsroom/${p.slug}.html`,
    title: p.meta.title,
    category: p.meta.category,
    tags: p.tags,
    date: f.date,
    dateNumeric: f.dateNumeric,
    dateISO: f.dateISO,
    groupKey: f.groupKey,
    groupLabel: f.groupLabel,
    excerpt: p.excerpt
  };
  if(p.meta.tabWord) a.tabWord = p.meta.tabWord;
  if(p.meta.image) a.image = p.meta.image;
  return a;
});
posts.forEach((p, i) => writeFileSync(join(OUT_DIR, `${p.slug}.html`), pageHtml(p, index[i])));

writeFileSync(DATA_FILE, `/* =====================================================================
   hlw-articles.js — ${GENERATED_MARK}. DO NOT EDIT BY HAND.

   The list of every published post (newest first), without the article
   text. The newsroom page (news.html), the homepage card stack and the
   homepage marquee all read this array.

   To publish, change or remove a post, edit the files in /articles
   (see articles/README.md). The build rewrites this file and the pages
   in /newsroom automatically.
   ===================================================================== */
const ARTICLES = ${JSON.stringify(index, null, 2)};
`);

console.log(`Built ${posts.length} article${posts.length === 1 ? '' : 's'}: ${posts.map(p => p.slug).join(', ') || '(none)'}`);
